const toModel = (e: Entry): Model => {
  const [src, width, height] = e.hero;
  const label = `${e.name} — ${e.desc}`;
  const gallery: Img[] = (e.gallery ?? []).map(([w, h], i) => ({
    src: `/assets/models/${e.slug}/g${i + (e.galleryStart ?? 1)}.jpg`, width: w, height: h, alt: `${e.name} — зураг`
  }));
  const stats: Stat[] = e.stats.map(([value, unit, statLabel]) => ({ value, unit, label: statLabel }));
  return {
    slug: e.slug, name: e.name, desc: e.desc, quick: e.quick,
    page: {
      tagline: e.tagline,
      hero: { kind: "intro", image: { src, width, height, alt: label }, maxWidth: Math.min(1100, Math.round(width * 1.5)) },
      stats, statsSecondary: "specs", gallery, specTable: e.specTable ?? true,
      end: {
        title: "Туршаад үзэх үү?",
        text: "Ойролцоох салбартаа туршилтын жолоодлого захиалж, ногоон зээл болон урьдчилсан захиалгын нөхцөлөө тодруулаарай.",
        secondary: { label: "Ногоон зээл", href: "#" }
      },
      notes: [
        "Явах зай нь стандарт туршилтын (CLTC, WLTC, NEDC, CHTC) үр дүн. Бодит зай нь тохиргоо, ачаа, зайны насжилт, жолоодлогын зуршил, цаг агаар, замын нөхцөлөөс хамаарна.",
        `${SOURCE[e.source ?? "factory"]} Техникийн хүснэгт нь машин орчуулга бөгөөд Монголд нийлүүлэх тохиргоог салбараас тодруулна уу.`,
        "Үзүүлэлт, тохиргоо нь урьдчилан мэдэгдэлгүйгээр өөрчлөгдөж болно. Зурагт харуулсан машин бодит машинаас ялгаатай байж болно."
      ]
    }
  };
};

export const catalogModels: Model[] = entries.map(toModel);
